import { Alert, SpaceBetween } from "@cloudscape-design/components";
import { useState } from "react";
import { ActionDialog } from "#/components/ActionDialog";
import { Action, Buttons, Field, Rows } from "#/components/containers/Controls";
import { batch, codebuildCall, list } from "#/lib/codebuild";
import {
	type Report,
	type ReportGroup,
	reportGroupInput,
	type Scope,
	type TestCase,
} from "#/lib/codebuildHelpers";
import { unixTime } from "#/lib/format";
import { tagMap } from "#/lib/tags";
import { usePoll } from "#/lib/usePoll";

export function ReportGroups({
	scope,
	enabled,
}: {
	scope: Scope;
	enabled: boolean;
}) {
	const [group, setGroup] = useState<ReportGroup>(),
		[report, setReport] = useState<Report>();
	const [dialog, setDialog] = useState(""),
		[name, setName] = useState(""),
		[tags, setTags] = useState("{}");
	const poll = usePoll(async () => {
		if (!enabled) return { groups: [] };
		const groups = await batch<ReportGroup>(
			scope,
			"BatchGetReportGroups",
			"ReportGroups",
			"ReportGroupArns",
			await list<string>(scope, "ListReportGroups", "ReportGroups"),
		);
		return { groups };
	}, 0);
	const selectGroup = (g?: ReportGroup) => {
		setGroup(g);
		setReport(undefined);
	};
	// Selection remounts the report view to load its reports and test cases.
	return (
		<SpaceBetween size="m">
			{!!poll.error && <Alert type="error">{poll.error}</Alert>}
			<Rows
				title="Report groups"
				items={poll.data?.groups ?? []}
				loading={poll.loading}
				emptyText="Create a TEST report group. Reports are generated by builds, not by a public create-report API."
				actions={
					<Buttons>
						<Action onClick={poll.reload}>Refresh</Action>
						<Action
							disabled={!enabled}
							onClick={() => {
								setName("");
								setTags("{}");
								setDialog("create");
							}}
						>
							Create report group
						</Action>
					</Buttons>
				}
				columns={[
					{
						id: "name",
						header: "Name",
						cell: (g) => (
							<Action onClick={() => selectGroup(g)}>{g.Name}</Action>
						),
					},
					{ id: "type", header: "Type", cell: (g) => g.Type },
					{
						id: "created",
						header: "Created",
						cell: (g) => unixTime(g.Created),
					},
					{
						id: "actions",
						header: "Actions",
						cell: (g) => (
							<Buttons>
								<Action
									disabled={!enabled}
									onClick={() => {
										selectGroup(g);
										setName(g.Name);
										setTags(JSON.stringify(tagMap(g.Tags), null, 2));
										setDialog("edit");
									}}
								>
									Edit
								</Action>
								<Action
									disabled={!enabled}
									onClick={() => {
										selectGroup(g);
										setDialog("delete");
									}}
								>
									Delete
								</Action>
							</Buttons>
						),
					},
				]}
			/>
			{enabled && (
				<ReportViews
					key={`${group?.Arn}/${report?.Arn}`}
					scope={scope}
					group={group}
					report={report}
					onReport={setReport}
				/>
			)}
			{!!dialog && (
				<ActionDialog
					title={`${dialog} report group`}
					submit={
						dialog === "delete" ? "Delete report group" : "Save report group"
					}
					confirmation={dialog === "delete" ? group?.Name : undefined}
					onClose={() => setDialog("")}
					onSaved={() => {
						setDialog("");
						selectGroup(undefined);
						poll.reload();
					}}
					plan={async () => {
						const op =
							dialog === "create"
								? "CreateReportGroup"
								: dialog === "edit"
									? "UpdateReportGroup"
									: "DeleteReportGroup";
						const input =
							dialog === "delete"
								? { Arn: group?.Arn, DeleteReports: true }
								: reportGroupInput(
										name,
										tags,
										dialog === "edit" ? group?.Arn : undefined,
									);
						return [{ label: op, run: () => codebuildCall(scope, op, input) }];
					}}
				>
					<SpaceBetween size="m">
						{dialog === "delete" ? (
							<Alert type="warning">
								Delete {group?.Name} and all its reports and test cases.
							</Alert>
						) : (
							<SpaceBetween size="m">
								{dialog === "edit" ? (
									<Alert>{group?.Name}</Alert>
								) : (
									<Field label="Name" value={name} onChange={setName} />
								)}
								<Alert>TEST reports with NO_EXPORT.</Alert>
								<Field
									label="Tags (JSON object)"
									value={tags}
									onChange={setTags}
									multiline
								/>
							</SpaceBetween>
						)}
					</SpaceBetween>
				</ActionDialog>
			)}
		</SpaceBetween>
	);
}
function ReportViews({
	scope,
	group,
	report,
	onReport,
}: {
	scope: Scope;
	group?: ReportGroup;
	report?: Report;
	onReport: (r: Report) => void;
}) {
	const poll = usePoll(async () => {
		const ids = await list<string>(
			scope,
			group ? "ListReportsForReportGroup" : "ListReports",
			"Reports",
			group ? { ReportGroupArn: group.Arn } : {},
		);
		const reports = await batch<Report>(
			scope,
			"BatchGetReports",
			"Reports",
			"ReportArns",
			ids,
		);
		const cases = report
			? await list<TestCase>(scope, "DescribeTestCases", "TestCases", {
					ReportArn: report.Arn,
				})
			: [];
		return { reports, cases };
	}, 0);
	return (
		<SpaceBetween size="m">
			{!!poll.error && <Alert type="error">{poll.error}</Alert>}
			<Rows
				title={group ? `Reports: ${group.Name}` : "Reports"}
				items={poll.data?.reports ?? []}
				loading={poll.loading}
				emptyText="No reports. Records mode does not execute builds or generate reports."
				actions={<Action onClick={poll.reload}>Refresh</Action>}
				columns={[
					{
						id: "name",
						header: "Report",
						cell: (r) => <Action onClick={() => onReport(r)}>{r.Name}</Action>,
					},
					{ id: "status", header: "Status", cell: (r) => r.Status },
					{
						id: "created",
						header: "Created",
						cell: (r) => unixTime(r.Created),
					},
					{
						id: "tests",
						header: "Tests",
						cell: (r) => r.TestSummary?.Total ?? 0,
					},
				]}
			/>
			{!!report && (
				<Rows
					title={`Test cases: ${report.Name}`}
					items={poll.data?.cases ?? []}
					loading={poll.loading}
					emptyText="No test cases."
					columns={[
						{ id: "name", header: "Name", cell: (c) => c.Name },
						{ id: "suite", header: "Suite", cell: (c) => c.TestSuiteName },
						{ id: "status", header: "Status", cell: (c) => c.Status },
						{
							id: "duration",
							header: "Duration (ns)",
							cell: (c) => c.DurationInNanoSeconds,
						},
						{ id: "message", header: "Message", cell: (c) => c.Message },
					]}
				/>
			)}
		</SpaceBetween>
	);
}
