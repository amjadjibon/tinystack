#!/bin/sh
# Prints the Homebrew formula for a release from its checksums.txt, for the amjadjibon/homebrew-tap repository.
# Usage: scripts/homebrew-formula.sh 0.0.2 dist/checksums.txt
set -eu

version=${1:?usage: homebrew-formula.sh <version> <checksums.txt>}
checksums=${2:?usage: homebrew-formula.sh <version> <checksums.txt>}
version=${version#v}
base="https://github.com/amjadjibon/tinystack/releases/download/v$version"

# archive prints the url and sha256 lines for one platform, failing if checksums.txt lacks its archive.
archive() {
	name="tinystack_${version}_$1_$2.tar.gz"
	sum=$(awk -v n="$name" '$2 == n { print $1 }' "$checksums")
	[ -n "$sum" ] || { echo "no checksum for $name in $checksums" >&2; exit 1; }
	printf '      url "%s/%s"\n      sha256 "%s"\n' "$base" "$name" "$sum"
}

cat <<EOF
# Generated by tinystack scripts/homebrew-formula.sh for v$version. Do not edit by hand.
class Tinystack < Formula
  desc "Local AWS service emulator in a single binary, with a web console"
  homepage "https://github.com/amjadjibon/tinystack"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(archive darwin arm64)
    end
    on_intel do
$(archive darwin amd64)
    end
  end

  on_linux do
    on_arm do
$(archive linux arm64)
    end
    on_intel do
$(archive linux amd64)
    end
  end

  def install
    bin.install "tinystack"
  end

  def caveats
    <<~EOS
      Homebrew manages this install; upgrade it with \`brew upgrade tinystack\`, not \`tinystack update\`.
    EOS
  end

  test do
    assert_match "tinystack version #{version}", shell_output("#{bin}/tinystack version")
  end
end
EOF
