#!/usr/bin/env python3
"""Render checked-in service coverage from curated notes and pinned AWS profiles."""

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "docs/site"
REPO = "https://github.com/amjadjibon/tinystack"
PROTOCOLS = {
    "awsJson1_0": "AWS JSON 1.0",
    "awsJson1_1": "AWS JSON 1.1",
    "awsQuery": "AWS Query",
    "ec2Query": "EC2 Query",
    "restXml": "REST XML",
    "restJson1": "REST JSON",
    "rpcv2Cbor": "Smithy RPC v2 CBOR",
}


def read_json(path):
    return json.loads((ROOT / path).read_text())


def source(path, label=None):
    view = "tree" if (ROOT / path).is_dir() else "blob"
    return f"[{label or path}]({REPO}/{view}/main/{path})"


def descriptor(key):
    code = (ROOT / f"internal/aws/generated/{key}/api.go").read_text()
    signing = re.search(r'SigningName: "([^"]+)"', code).group(1)
    protocols = re.search(r'Protocols: \[\]string\{([^}]+)\}', code).group(1)
    interface = re.search(r'type API interface \{(.*?)\n\}', code, re.S).group(1)
    operations = set(re.findall(r'^\s*(\w+)\(', interface, re.M))
    return signing, [PROTOCOLS[p] for p in re.findall(r'"([^"]+)"', protocols)], operations


def bullets(items):
    return "\n".join(f"- {item}." if not item.endswith(".") else f"- {item}" for item in items)


def anchor(title):
    return re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", title).strip().lower())


def service_page(key, info, profile, manifest):
    model = read_json(f"generator/model/{key}.json")
    shapes = model["shapes"]
    service = next(s for s in shapes.values() if s["type"] == "service")
    modeled = {name.split("#")[-1]: s for name, s in shapes.items() if s["type"] == "operation"}
    enabled = set(profile["operations"])
    signing, protocols, generated = descriptor(key)
    if enabled != generated or not enabled <= modeled.keys():
        raise ValueError(f"{key}: profile, generated interface, and model operations differ; run task generate")
    unsupported = sorted(modeled.keys() - enabled)
    scope = "Account-wide" if key in {"iam", "route53", "cloudfront", "account"} else "Account and region"
    rows = []
    for name in sorted(enabled):
        http = modeled[name].get("traits", {}).get("smithy.api#http", {})
        route = f"{http.get('method', 'POST')} {http.get('uri', '/')}"
        route = route.replace("|", "\\|")
        rows.append(f"| `{name}` | `{route}` |")
    tests = sorted((ROOT / "tests/integration").glob(f"{info.get('tests', info['package'])}*_test.go"))
    test_links = ", ".join(source(str(p.relative_to(ROOT)), p.name) for p in tests)
    omitted = "All operations in this pinned model are selected. Member and behavior limits still apply."
    if unsupported:
        names = "\n".join(f"    - `{name}`" for name in unsupported)
        noun = "operation" if len(unsupported) == 1 else "operations"
        omitted = (
            f'??? info "{len(unsupported)} modeled {noun} outside the implementation"\n\n'
            "    These operations are absent from the profile. This is a coverage inventory, not a delivery commitment.\n\n"
            + names
        )
    return f"""<!-- Generated by scripts/docs.py; edit docs/catalog.json and run task docs:generate. -->
# {info['title']}

{info['summary']}

**Status: implemented subset.** Operation selection does not imply complete input or behavior parity.

| Contract | Current implementation |
| --- | --- |
| Service ID | `{key}` |
| Signing name | `{signing}` |
| Wire protocol | {', '.join(protocols)} |
| API version | `{service['version']}` |
| Scope | {scope} |
| Execution | {info['execution']} |
| Selected operations | {len(enabled)} of {len(modeled)} in the pinned model |

## Implemented behavior

See the [implemented feature catalogue](catalogue.md#{anchor(info['title'])}) for this service's capabilities.

## Limitations and future work

{bullets(info['gaps'])}

These gaps describe current boundaries and possible follow-up slices. The [roadmap](../roadmap/index.md)
separates proposed work from registered functionality; there are no promised release dates.

## Supported operations

The table is generated from the profile and pinned Smithy model. Routes show REST bindings or the standard
JSON/Query endpoint. RPC v2 CBOR uses its service/operation route, as described in
[protocol handling](../architecture/request-flow.md). Supported members are selected separately in the
{source('generator/model/profile.json', 'shape whitelist')}; an enabled operation may reject unsupported options.

| Operation | HTTP binding |
| --- | --- |
{chr(10).join(rows)}

## Operations not implemented

{omitted}

## Source and examples

- {source(f"internal/services/{info['package']}", 'Service implementation')}
- {source(f'internal/aws/generated/{key}/api.go', 'Generated API interface and descriptor')}
- {source(f'generator/model/{key}.json', 'Pinned upstream model')} at `{manifest['commit']}`.
- SDK integration examples: {test_links or source('tests/integration', 'integration suite')}.
- [Connect a client](../getting-started/clients.md) and [inspect requests](../guides/diagnostics.md).
"""


def future_page(key, info):
    kind = info['state']
    specifics = ""
    for field, title in [("integration", "Integration decisions"), ("acceptance", "Service-specific acceptance checks")]:
        if info.get(field):
            specifics += f"\n## {title}\n\n{info[field]}\n"
    return f"""<!-- Generated by scripts/docs.py; edit docs/catalog.json and run task docs:generate. -->
# {info['title']}

**Status: {kind.lower()}.** This service or extension is not implemented in the registered API profiles.
The scope below is a design candidate, without an assigned version or delivery date.

## First useful slice

{info['slice']}

## Proposed scope

{info['features']}
{specifics}

## Decisions before implementation

Use the shared [implementation decisions](../index.md#decisions-before-implementation).

## Acceptance criteria

Apply the shared [acceptance criteria](../index.md#acceptance-criteria) alongside any service-specific checks above.

Follow [adding a service](../../development/adding-services.md). See the [roadmap](../index.md) for shared priorities.
"""


def render():
    parallel_docs = sorted(
        str(path.relative_to(ROOT))
        for path in (ROOT / "docs").rglob("*.md")
        if not path.is_relative_to(SITE)
    )
    if parallel_docs:
        raise ValueError("Keep product Markdown under docs/site; consolidate parallel docs:\n" + "\n".join(parallel_docs))
    catalog = read_json("docs/catalog.json")
    profiles = read_json("generator/model/profile.json")
    manifest = read_json("generator/model/manifest.json")
    if set(catalog["services"]) != set(profiles):
        raise ValueError("Service catalogue and profiles differ; document every enabled service")
    registered = set(re.findall(r'\b(\w+)api\.Descriptor\(', (ROOT / "internal/app/app.go").read_text()))
    if registered != set(profiles):
        raise ValueError("Startup registrations and profiles differ; audit the service catalogue")
    groups = defaultdict(list)
    pages = {}
    for key, info in sorted(catalog["services"].items(), key=lambda pair: pair[1]["title"]):
        if not info["features"]:
            raise ValueError(f"{key}: document at least one implemented feature")
        pages[f"services/{key}.md"] = service_page(key, info, profiles[key], manifest)
        groups[info["category"]].append((key, info))
    for key, info in catalog["future"].items():
        pages[f"roadmap/services/{key}.md"] = future_page(key, info)
    count = sum(len(p["operations"]) for p in profiles.values())
    index = [
        "<!-- Generated by scripts/docs.py. -->", "# Service support", "",
        f"TinyStack registers **{len(profiles)} service APIs** with **{count:,} selected operations**.", "",
        "Every API below implements a subset. Counts describe operation selection in the pinned models, not AWS parity.",
        "Use a service page for behavior, limitations, exact operation names, wire routes, and SDK examples.", "",
        "Browse the [implemented services and features catalogue](catalogue.md) for the full capability inventory.", "",
        "Future services and unimplemented extensions live in the [roadmap](../roadmap/index.md).", "",
    ]
    inventory = [
        "<!-- Generated by scripts/docs.py; edit docs/catalog.json and run task docs:generate. -->",
        "# Implemented services and features", "",
        f"TinyStack implements **{len(profiles)} service APIs** with **{count:,} selected operations**.", "",
        "This catalogue records the capabilities available in the current checkout. Each service implements a subset;",
        "its reference documents supported operations, inputs, and behavior limits. Execution modes show when a",
        "feature manages records or needs a Docker runtime.", "",
        "## Shared platform features", "",
        "| Feature | Implemented behavior | Reference |", "| --- | --- | --- |",
    ]
    for feature in catalog["platform_features"]:
        inventory.append(
            f"| {feature['title']} | {feature['summary']} | [Details](../{feature['reference']}) |"
        )
    inventory += ["", "## Service features", "",
                  "Use the [support matrix](index.md) to compare operation counts and execution modes.", ""]
    nav = ["  - Services:", "      - Support matrix: services/index.md",
           "      - Implemented catalogue: services/catalogue.md"]
    for category, items in sorted(groups.items()):
        index += [f"## {category}", "", "| Service API | Operations | Execution |", "| --- | --- | --- |"]
        inventory += [f"### {category}", ""]
        nav += [f"      - {json.dumps(category)}:"]
        for key, info in items:
            index.append(f"| [{info['title']}]({key}.md) | {len(profiles[key]['operations'])} | {info['execution']} |")
            inventory += [
                f"#### {info['title']}", "", info["summary"], "",
                f"**Execution:** {info['execution']}. **Selected operations:** {len(profiles[key]['operations'])}.", "",
                bullets(info["features"]), "",
                f"[Supported operations]({key}.md#supported-operations) · "
                f"[Limitations]({key}.md#limitations-and-future-work)", "",
            ]
            nav.append(f"          - {json.dumps(info['title'])}: services/{key}.md")
        index.append("")
    pages["services/index.md"] = "\n".join(index)
    inventory += ["## Keep the catalogue current", "",
                  "Feature descriptions live in `docs/catalog.json`; operation counts come from registered profiles.",
                  "Update the catalogue with each delivered service or feature, then run `task docs:generate` and",
                  "`task docs:check`. CI rejects stale generated pages and undocumented registered services.", "",
                  "See the [documentation workflow](../development/documentation.md) for maintenance.",
                  "Proposed additions remain in the [future catalogue](../roadmap/catalogue.md).", ""]
    pages["services/catalogue.md"] = "\n".join(inventory)
    future_index = ["<!-- Generated by scripts/docs.py. -->", "# Future service catalogue", "",
                    "These designs are candidates; none of the surfaces below is registered as an implemented API.",
                    "Some extend an existing service, while others add a new service or runtime.",
                    "A proposal is not a release commitment. See the [roadmap](index.md) for priorities.", "",
                    "| Service or extension | Status | First useful slice |", "| --- | --- | --- |"]
    nav += ["  - Roadmap:", "      - Priorities and policy: roadmap/index.md", "      - Future catalogue: roadmap/catalogue.md",
            "      - Service and extension proposals:"]
    for key, info in sorted(catalog["future"].items(), key=lambda pair: pair[1]["title"]):
        future_index.append(f"| [{info['title']}](services/{key}.md) | {info['state']} | {info['slice'].replace('|', '/')} |")
        nav.append(f"          - {json.dumps(info['title'])}: roadmap/services/{key}.md")
    pages["roadmap/catalogue.md"] = "\n".join(future_index) + "\n"
    resources = {}
    for file in sorted((ROOT / "internal/services/cloudformation").glob("resources*.go")):
        for name in re.findall(r'\bregister\w*\("(AWS::[^"\s]+)"', file.read_text()):
            if name in resources:
                raise ValueError(f"Duplicate CloudFormation registration: {name}")
            resources[name] = file.relative_to(ROOT).as_posix()
    if not resources:
        raise ValueError("No CloudFormation registrations found")
    pages["guides/cloudformation-resources.md"] = (
        "<!-- Generated by scripts/docs.py. -->\n# CloudFormation resource types\n\n"
        f"The resource registry contains **{len(resources)} types**. Each type supports only its registered properties "
        "and attributes. The linked source defines that subset; an SDK operation existing does not imply "
        "CloudFormation support.\n\nSee [infrastructure workflows](infrastructure.md) for SAM and Terraform.\n\n"
        "| Resource type | Definition |\n| --- | --- |\n"
        + "\n".join(f"| `{name}` | {source(path, Path(path).name)} |" for name, path in sorted(resources.items())) + "\n"
    )
    config = (ROOT / "mkdocs.yml").read_text()
    block = "  # GENERATED NAV START\n" + "\n".join(nav) + "\n  # GENERATED NAV END"
    config, replacements = re.subn(r"  # GENERATED NAV START\n.*?  # GENERATED NAV END", lambda _: block, config, flags=re.S)
    if replacements != 1:
        raise ValueError("mkdocs.yml must contain exactly one generated nav block")
    outputs = {SITE / path: content for path, content in pages.items()}
    outputs[ROOT / "mkdocs.yml"] = config
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated docs are stale")
    args = parser.parse_args()
    outputs = render()
    stale = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    expected = set(outputs)
    obsolete = []
    for directory in [SITE / "services", SITE / "roadmap/services"]:
        for path in directory.glob("*.md"):
            if path not in expected:
                obsolete.append(str(path.relative_to(ROOT)))
    if obsolete:
        parser.exit(1, "Obsolete service pages need review/removal:\n" + "\n".join(obsolete) + "\n")
    if stale:
        parser.exit(1, "Run task docs:generate; stale documentation:\n" + "\n".join(stale) + "\n")
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} documentation files")


if __name__ == "__main__":
    main()
